package cn.chahuyun.economy.actionchain.ksp

/** Emits the facade and module-descriptor sources consumed by KSP. No reflection, only static calls. */
internal object ActionCodeGenerator {

    private const val GENERATED_HEADER = "// Generated by economy-action-ksp. Do not edit."

    /** One file per annotated object; every `@Action` member becomes a facade function. */
    fun facadeFile(
        packageName: String,
        ownerSimpleName: String,
        ownerQualifiedName: String,
        actions: List<ActionDecl>,
    ): String = buildString {
        appendLine(GENERATED_HEADER)
        appendLine("package $packageName")
        appendLine()
        appendLine("import cn.chahuyun.economy.actionchain.runtime.ActionExecution")
        appendLine("import cn.chahuyun.economy.actionchain.runtime.ActionRuntime")
        appendLine()
        appendLine("public object ${ownerSimpleName}Actions {")
        actions.forEachIndexed { index, action ->
            if (index > 0) appendLine()
            val returnType = if (action.returnsUnit) "Unit" else action.returnType!!.renderType()
            val contextArg = if (action.injectContext) ", context" else ""
            val lambdaParam = if (action.injectContext) "context" else "_"
            appendLine("    public suspend fun ${action.functionName}(event: ${action.eventType.renderType()}): " +
                "ActionExecution<$returnType> =")
            appendLine("        ActionRuntime.invoke(")
            appendLine("            actionId = \"${action.actionId.escapeKotlin()}\",")
            appendLine("            event = event,")
            appendLine("        ) { $lambdaParam ->")
            appendLine("            $ownerQualifiedName.${action.functionName}(event$contextArg)")
            appendLine("        }")
        }
        appendLine("}")
    }

    /** The single per-module descriptor aggregated by `economy-main`. */
    fun moduleFile(
        packageName: String,
        objectName: String,
        moduleId: String,
        actionIds: List<String>,
        rules: List<RuleDecl>,
        providers: List<ProviderDecl>,
    ): String = buildString {
        appendLine(GENERATED_HEADER)
        appendLine("package $packageName")
        appendLine()
        appendLine("import cn.chahuyun.economy.actionchain.runtime.ActionContext")
        appendLine("import cn.chahuyun.economy.actionchain.runtime.ActionModule")
        appendLine("import cn.chahuyun.economy.actionchain.runtime.ActionRule")
        appendLine("import cn.chahuyun.economy.actionchain.runtime.ActionResult")
        appendLine("import cn.chahuyun.economy.actionchain.runtime.actionProvider")
        appendLine()
        appendLine("public object $objectName {")
        appendLine("    public val module: ActionModule = ActionModule(")
        appendLine("        moduleId = \"${moduleId.escapeKotlin()}\",")
        append("        actionIds = ")
        appendSet(actionIds)
        appendLine(",")
        appendLine("        rules = listOf(")
        rules.forEach { rule -> appendRule(rule) }
        appendLine("        ),")
        appendLine("        providers = listOf(")
        providers.forEach { provider -> appendProvider(provider) }
        appendLine("        ),")
        appendLine("    )")
        appendLine("}")
    }

    private fun StringBuilder.appendSet(values: List<String>) {
        if (values.isEmpty()) {
            append("emptySet()")
            return
        }
        append("setOf(")
        append(values.joinToString(", ") { "\"${it.escapeKotlin()}\"" })
        append(")")
    }

    private fun StringBuilder.appendRule(rule: RuleDecl) {
        val factory = if (rule.stage == RuleStage.BEFORE) "ActionRule.before" else "ActionRule.after"
        // 规则没有任何参数时用 `_`，避免生成代码产生 unused parameter 警告。
        val contextParam = if (rule.parameters.isEmpty()) "_" else "context"
        appendLine("            $factory(")
        appendLine("                actionId = \"${rule.actionId.escapeKotlin()}\",")
        appendLine("                ruleId = \"${rule.ruleId.escapeKotlin()}\",")
        appendLine("                order = ${rule.order},")
        appendLine("                invoke = { $contextParam: ActionContext ->")
        appendLine("                    ${rule.owner}.${rule.functionName}(")
        rule.parameters.forEach { parameter ->
            append("                        ")
            append(
                when (parameter) {
                    ParamBinding.Context -> "context"
                    is ParamBinding.FromProvider -> {
                        val literal = parameter.type.renderClassLiteral()
                            ?: error("Unsupported provider parameter type ${parameter.type.renderType()}")
                        val qualifier = parameter.qualifier
                        if (qualifier == null) {
                            "context.provide($literal::class)"
                        } else {
                            "context.provide($literal::class, \"${qualifier.escapeKotlin()}\")"
                        }
                    }
                }
            )
            appendLine(",")
        }
        appendLine("                    )")
        if (!rule.returnsActionResult) {
            appendLine("                    ActionResult.Continue")
        }
        appendLine("                },")
        appendLine("            ),")
    }

    private fun StringBuilder.appendProvider(provider: ProviderDecl) {
        val valueType = provider.valueType.renderType()
        val actionId = provider.actionId?.let { "\"${it.escapeKotlin()}\"" } ?: "null"
        appendLine("            actionProvider<$valueType>(")
        appendLine("                qualifier = \"${provider.qualifier.escapeKotlin()}\",")
        appendLine("                actionId = $actionId,")
        if (provider.takesContext) {
            appendLine("                load = { context -> ${provider.owner}.${provider.functionName}(context) },")
        } else {
            appendLine("                load = { ${provider.owner}.${provider.functionName}() },")
        }
        appendLine("            ),")
    }
}
